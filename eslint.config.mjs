/**
 * @fileoverview ESLint flat config for the whole repository.
 *
 * @description
 * Composes the Next.js Core Web Vitals and TypeScript rule sets, which already
 * include React hooks rules, unused-variable detection and the Next-specific
 * rules (no `<img>`, no sync scripts, and so on). Build output and generated
 * types are ignored so lint runs on source only.
 *
 * @implementation
 *
 * Step 1: Load the two `eslint-config-next` presets.
 * Step 2: Register them with `defineConfig`.
 * Step 3: Ignore generated directories (`.next`, `out`, `build`) and
 *         `next-env.d.ts` (regenerated by `next dev`).
 * Step 4: Run with `bun run lint`; it must report zero problems.
 * Step 5: Used by editors and CI; failures block the change.
 * Step 6: New source directories are covered automatically (no glob list).
 *
 * @author HMS team
 * @version 1.0.0
 * @since 2026-10-24
 */

import { defineConfig, globalIgnores } from "eslint/config";
import nextVitals from "eslint-config-next/core-web-vitals";
import nextTs from "eslint-config-next/typescript";

const eslintConfig = defineConfig([
  ...nextVitals,
  ...nextTs,
  // Override default ignores of eslint-config-next.
  globalIgnores([
    // Default ignores of eslint-config-next:
    ".next/**",
    "out/**",
    "build/**",
    "next-env.d.ts",
  ]),
]);

export default eslintConfig;
