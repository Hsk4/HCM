/**
 * @fileoverview Root layout: fonts, global styles and the document shell.
 *
 * @description
 * Every route renders inside this layout. It loads the Geist sans/mono faces as
 * CSS variables (consumed by `@theme` in `app/globals.css`), sets full-height
 * document sizing, and deliberately contains **no** data access — the session
 * is read in the role layouts (`app/(app)/{admin,hr,employee}/layout.tsx`) so
 * `/login` and `/setup` stay cheap and unauthenticated.
 *
 * @implementation
 *
 * Step 1: Register the two font families via `next/font` (self-hosted, no
 *         network request at runtime, no layout shift).
 * Step 2: Import global Tailwind CSS.
 * Step 3: Export metadata (title/description).
 * Step 4: Render `<html>`/`<body>`; `LayoutProps<"/">` is generated by Next and
 *         typed per route.
 * Step 5: Children are the role layout → page tree.
 * Step 6: Each page must render with the expected fonts and no unstyled flash.
 *
 * @author HMS team
 * @version 1.0.0
 * @since 2026-10-24
 */

import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "HCM Lite",
  description: "Human capital management: attendance, leave, payroll and an AI assistant.",
};

/**
 * Renders the document shell around every route.
 *
 * @param props `children` — the matched route tree.
 * @returns The `<html>`/`<body>` wrapper.
 */
export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">{children}</body>
    </html>
  );
}
